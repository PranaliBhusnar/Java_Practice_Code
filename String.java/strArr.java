import java.util.*;
public class strArr{
    public static vid main(String[] args){
        Scanner sc=new Scanner(System.in);
        // String s=sc.nextLine;
        int n=sc.nextInt;
        char[] arr=new char[n];
         for(char ele:arr){
             arr[ele]=sc.nextLine;
        }
        for(char ele:arr){
            System.out.print(ele+" ");
        }
    }
}